import assert from 'node:assert/strict';
import {nextAction,pickups,phoneLink,mapLink,canClaim,earningsForPeriod,earningsSummary} from '../courier-model.js';
import {makePreview} from '../courier-preview.js';
const preview=makePreview(),job=preview.active[0],stops=preview.stops.get(job.id);
assert.equal(pickups(job,stops).length,2);
assert.equal(nextAction({...job,status:'accepted'},2).label,'Все точки забраны');
assert.equal(nextAction({...job,status:'assigned'}).action,'accepted');
assert.equal(nextAction({...job,status:'picked_up'}).action,'delivered');
for(const status of ['delivered','cancelled','new'])assert.equal(nextAction({...job,status}),null);
assert.equal(phoneLink('+380 (50) 123-45-67'),'tel:+380501234567');
assert.equal(phoneLink('javascript:alert(1)'),null);
assert.equal(new URL(mapLink('Теплодар, дом 2 & подъезд 1')).searchParams.get('query'),'Теплодар, дом 2 & подъезд 1');
for(const opts of [{activeCount:2,shift:true},{activeCount:0,shift:false},{activeCount:0,shift:true,busy:true},{activeCount:0,shift:true,online:false}])assert.equal(canClaim({...opts,role:'courier'}),false);
assert.equal(canClaim({activeCount:1,shift:true,role:'courier'}),true);
assert.equal(canClaim({activeCount:0,shift:false,role:'admin'}),true);
const now=Date.parse('2026-11-19T22:30:00Z'),rows=[{job_id:'a',amount_uah:55,recorded_at:'2026-11-19T22:10:00Z'},{job_id:'b',amount_uah:45,recorded_at:'2026-11-19T19:00:00Z'},{job_id:'c',amount_uah:50,recorded_at:'2026-11-12T12:00:00Z'}];
assert.equal(earningsForPeriod(rows,'today',now).length,1,'use Kyiv day, including after UTC midnight boundary');
assert.equal(earningsForPeriod(rows,'week',now).length,2);
assert.deepEqual(earningsSummary(earningsForPeriod(rows,'all',now)),{total:150,count:3,average:50});
assert.deepEqual(earningsSummary([]),{total:0,count:0,average:0});
assert.equal(makePreview('empty').active.length,0);
console.log('PASS: route stages, combined pickups, terminal guards, safe map/phone links, capacity/shift/offline guards, Kyiv earnings periods.');
